// empty rules file would otherwise pass the release gate.
module.exports.renderDataExtractionRules = renderDataExtractionRules;
module.exports.EXCLUDED_DOMAINS = EXCLUDED_DOMAINS;
module.exports.EXTRACTION_SECTIONS = EXTRACTION_SECTIONS;
module.exports.DOMAIN_ROOT_PATH = DOMAIN_ROOT_PATH;
module.exports.GENERATED_MARKER = GENERATED_MARKER;
