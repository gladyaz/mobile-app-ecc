const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Marker written into the generated `android/app/build.gradle`. Its only job
 * is idempotence: `expo prebuild` WITHOUT `--clean` re-runs the mods over the
 * file this plugin already rewrote, and the anchors below only exist in the
 * pristine template. Without this check the second prebuild would throw and
 * look like a broken plugin rather than a no-op.
 */
const MARKER = '// --- BEGIN release signing (plugins/with-android-release-signing.js) ---';

/**
 * The template's release build type, verbatim. Anchored on the surrounding
 * comment rather than on `signingConfig signingConfigs.debug` alone, because
 * that exact line also appears in the `debug` build type immediately above and
 * a bare replace would rewrite the wrong one.
 */
const TEMPLATE_RELEASE_SIGNING = `        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;

const TEMPLATE_SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

const TEMPLATE_ANDROID_BLOCK_START = `android {
    ndkVersion rootProject.ext.ndkVersion`;

/**
 * Groovy that resolves the release keystore credentials AT BUILD TIME.
 *
 * Read the property names carefully: nothing here is a value. This plugin runs
 * in Node during prebuild and never opens `keystore.properties`, never holds a
 * password in a JavaScript variable, and never writes one into a generated
 * file. It emits the code that makes GRADLE read them, on the machine doing
 * the build, from a file git refuses to track (`.gitignore`,
 * "Signing and service credentials"). That is the only place a password for
 * this project should ever exist.
 */
const RELEASE_SIGNING_RESOLUTION = `${MARKER}
//
// WHY THIS IS GENERATED AND NOT EDITED IN PLACE: \`android/\` is gitignored and
// regenerated by \`expo prebuild\`, so a release signingConfig typed into this
// file by hand is destroyed by the next prebuild - and the artifact after that
// one is debug-signed again, silently. Expressing it as a config plugin is the
// only form of it that survives.
//
// Credentials come from \`<repo-root>/keystore.properties\` (gitignored), or
// from the environment when a build machine has no such file:
//
//   storeFile=upload-keystore.jks      ANDROID_RELEASE_STORE_FILE
//   storePassword=...                  ANDROID_RELEASE_STORE_PASSWORD
//   keyAlias=upload                    ANDROID_RELEASE_KEY_ALIAS
//   keyPassword=...                    ANDROID_RELEASE_KEY_PASSWORD
//
// A relative \`storeFile\` is resolved from the REPOSITORY root, not from
// \`android/\`, so the same path works before and after a prebuild.
def eccReleaseKeystoreProperties = new Properties()
def eccReleaseKeystorePropertiesFile = new File(rootProject.projectDir.parentFile, 'keystore.properties')

if (eccReleaseKeystorePropertiesFile.exists()) {
    eccReleaseKeystorePropertiesFile.withInputStream { eccReleaseKeystoreProperties.load(it) }
}

def eccReleaseSigningValues = [
    storeFile: eccReleaseKeystoreProperties.getProperty('storeFile') ?: System.getenv('ANDROID_RELEASE_STORE_FILE'),
    storePassword: eccReleaseKeystoreProperties.getProperty('storePassword') ?: System.getenv('ANDROID_RELEASE_STORE_PASSWORD'),
    keyAlias: eccReleaseKeystoreProperties.getProperty('keyAlias') ?: System.getenv('ANDROID_RELEASE_KEY_ALIAS'),
    keyPassword: eccReleaseKeystoreProperties.getProperty('keyPassword') ?: System.getenv('ANDROID_RELEASE_KEY_PASSWORD'),
]

def eccReleaseSigningProvided = eccReleaseSigningValues.findAll { name, value -> value != null && !value.toString().trim().isEmpty() }
def eccReleaseSigningConfigured = eccReleaseSigningProvided.size() == eccReleaseSigningValues.size()

// A PARTIALLY filled keystore.properties is the one case that must stop the
// build. Falling back to debug signing there would answer a typo'd key name
// with a debug-signed "release" APK - exactly the silent outcome this plugin
// exists to remove. Only key NAMES are printed; a value never is.
if (!eccReleaseSigningConfigured && !eccReleaseSigningProvided.isEmpty()) {
    throw new GradleException(
        'Release signing is only partly configured. Provided: ' + eccReleaseSigningProvided.keySet() +
        '. Missing: ' + (eccReleaseSigningValues.keySet() - eccReleaseSigningProvided.keySet()) +
        '. Fill all four in keystore.properties (or the ANDROID_RELEASE_* environment variables), ' +
        'or clear all four to fall back to debug signing for an internal build.'
    )
}

def eccReleaseStoreFile = null

if (eccReleaseSigningConfigured) {
    def eccReleaseStoreFileCandidate = new File(eccReleaseSigningValues.storeFile.toString())

    if (eccReleaseStoreFileCandidate.isAbsolute()) {
        eccReleaseStoreFile = eccReleaseStoreFileCandidate
    } else {
        eccReleaseStoreFile = new File(rootProject.projectDir.parentFile, eccReleaseSigningValues.storeFile.toString())
    }

    if (!eccReleaseStoreFile.exists()) {
        throw new GradleException(
            'Release signing is configured but the keystore file does not exist at ' +
            eccReleaseStoreFile.absolutePath +
            '. A relative storeFile is resolved from the repository root.'
        )
    }
}

// Says which key an artifact is about to be signed with, in the build log,
// every time. "Debug-signed" being an unremarkable property of a file named
// app-release.apk is how a debug-signed build reaches an upload dialog.
if (eccReleaseSigningConfigured) {
    println '> release signing: project release keystore'
} else {
    println '> release signing: DEBUG keystore - internal artifacts only; Google Play rejects this'
}
// --- END release signing ---

`;

/**
 * Gives Android release builds a real signing config WHEN, and only when, this
 * machine has the credentials for one - and otherwise leaves the template's
 * debug signing exactly as it was.
 *
 * WHY THE FALLBACK IS DELIBERATE AND NOT LAZINESS: the internal LAN demo APK
 * (docs/android-local-demo.md) and the offline demo APK
 * (docs/android-offline-demo-apk.md) are both `assembleRelease`, and both are
 * built on machines that have no release keystore. More than that, the Google
 * OAuth Android client this project can actually sign in against today is
 * registered to the debug keystore's SHA-1. Hard-failing `assembleRelease`
 * without a keystore would break two working internal workflows in order to
 * chase a key that does not exist yet - so the absent case stays exactly as it
 * is, and `npm run release:preflight` is what refuses to call the result a
 * store artifact.
 *
 * The unsafe state is therefore not "debug-signed" - it is "debug-signed and
 * nobody said so". Both halves of this change close that: Gradle prints which
 * key it used, and the preflight blocks.
 */
module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    const contents = gradleConfig.modResults.contents;

    if (contents.includes(MARKER)) {
      return gradleConfig;
    }

    for (const anchor of [
      TEMPLATE_ANDROID_BLOCK_START,
      TEMPLATE_SIGNING_CONFIGS,
      TEMPLATE_RELEASE_SIGNING,
    ]) {
      if (!contents.includes(anchor)) {
        throw new Error(
          'with-android-release-signing: android/app/build.gradle does not match the Expo ' +
            'template this plugin patches. The anchor it could not find starts with: ' +
            `"${anchor.split('\n')[0].trim()}". Re-check the template before shipping - a ` +
            'plugin that silently skipped would leave the release build debug-signed.'
        );
      }
    }

    gradleConfig.modResults.contents = contents
      .replace(TEMPLATE_ANDROID_BLOCK_START, `${RELEASE_SIGNING_RESOLUTION}${TEMPLATE_ANDROID_BLOCK_START}`)
      .replace(
        TEMPLATE_SIGNING_CONFIGS,
        `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        // Declared only when credentials exist, so that referencing
        // \`signingConfigs.release\` below is itself the availability check.
        if (eccReleaseSigningConfigured) {
            release {
                storeFile eccReleaseStoreFile
                storePassword eccReleaseSigningValues.storePassword.toString()
                keyAlias eccReleaseSigningValues.keyAlias.toString()
                keyPassword eccReleaseSigningValues.keyPassword.toString()
            }
        }
    }`
      )
      .replace(
        TEMPLATE_RELEASE_SIGNING,
        `        release {
            // Groovy evaluates only the taken branch of a ternary, so
            // \`signingConfigs.release\` is not resolved - and does not have to
            // exist - on a machine with no release keystore.
            signingConfig eccReleaseSigningConfigured ? signingConfigs.release : signingConfigs.debug`
      );

    return gradleConfig;
  });
};
