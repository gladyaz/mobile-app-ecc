const fs = require('fs');
const path = require('path');

const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const CONFIG_RESOURCE = 'data_extraction_rules';

// Stamped into every file this plugin writes, and checked before it deletes
// one. Same rule as plugins/with-lan-cleartext-demo.js: a
// `data_extraction_rules.xml` that some other plugin (or a human) put there is
// none of this plugin's business - only what it generated itself may ever be
// removed.
const GENERATED_MARKER = 'GENERATED by plugins/with-android-data-extraction-rules.js';

const MANIFEST_ATTRIBUTE = 'android:dataExtractionRules';
const CONFIG_RESOURCE_REFERENCE = `@xml/${CONFIG_RESOURCE}`;

function resourceRelativePath(sourceSet) {
  return path.join('app', 'src', sourceSet, 'res', 'xml', `${CONFIG_RESOURCE}.xml`);
}

/**
 * The ONE source set this policy is written to.
 *
 * `main` applies to every variant, which is the property being bought: a
 * release APK and a debug APK deny exactly the same things. The sibling
 * cleartext plugin deliberately does the opposite (a `debug`-only override)
 * because Metro genuinely needs a permission a release build must not have.
 * Nothing about backup is like that - there is no development workflow that
 * needs the tokens to survive a cloud backup - so a per-variant override here
 * would be a divergence with no reason, and `removeStaleVariantResources`
 * below actively deletes one if it ever appears.
 */
const RESOURCE_RELATIVE_PATH = resourceRelativePath('main');

/**
 * The variant source sets the Expo prebuild template creates. A generated copy
 * in any of them would SHADOW the `main` policy for that variant only (Android
 * merges `src/<variant>/res` over `src/main/res`), which is the specific way
 * "debug and release quietly disagree about what may leave the device" would
 * happen.
 */
const VARIANT_SOURCE_SETS = ['debug', 'debugOptimized', 'release'];

const VARIANT_RESOURCE_RELATIVE_PATHS = VARIANT_SOURCE_SETS.map(resourceRelativePath);

/**
 * EVERY domain `android.app.backup.FullBackup.BackupScheme` can resolve, and
 * therefore every domain `BackupAgent.onFullBackup` walks.
 *
 * WHY THE LIST MUST BE EXHAUSTIVE RATHER THAN "root plus a couple". Two facts
 * from the platform source (checked against
 * `$ANDROID_SDK/sources/android-36.1/android/app/backup/`):
 *
 *  1. `BackupAgent.onFullBackup` runs a SEPARATE traversal per domain, each
 *     one starting at that domain's own directory - root, then device_root,
 *     then file, device_file, database, device_database, sharedpref,
 *     device_sharedpref, and finally external.
 *  2. `BackupAgent.manifestExcludesContainFilePath` compares with
 *     `excludePath.equals(filePath)` - EXACT path equality, not a prefix
 *     match. A directory is pruned only because the walk hits that exact
 *     directory and stops before enqueuing its children.
 *
 * Together those mean `<exclude domain="root" path="."/>` alone does NOT
 * exclude `databases/`: the database traversal starts at `databases/` and
 * never visits the data dir, so the root rule is never compared against
 * anything. Excluding the data directory is not the same as excluding the
 * things inside it. Hence one rule per domain.
 *
 * `external` resolves to `getExternalFilesDir(null)`, which may be null on a
 * device with no external storage; the parser then logs the rule as invalid
 * and skips it, which is harmless. This app blocks the external-storage
 * permissions outright (see `android.blockedPermissions` in app.json) and
 * writes nothing there, so the rule is belt-and-braces either way.
 */
const EXCLUDED_DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
  'external',
];

/**
 * "The domain directory itself."
 *
 * Android's documentation states that `path` is REQUIRED on every `<include>`
 * and `<exclude>`, and its own worked example uses `path="."` for exactly this
 * meaning. (The platform parser is in fact laxer - `FullBackup`'s
 * `extractCanonicalFile` substitutes `""` for a missing path - but writing the
 * documented form costs nothing and does not rely on that leniency.) `.` is
 * canonicalised away by `File.getCanonicalPath()`, so the rule resolves to the
 * same string `tokenToDirectoryPath` hands the traversal, which is what makes
 * the exact-equality prune above fire.
 */
const DOMAIN_ROOT_PATH = '.';

/**
 * The two operations Android will run against this app's private storage, each
 * configured by its own section.
 *
 * BOTH are listed on purpose, and neither is redundant:
 *
 * - `cloud-backup` is already dead via `android:allowBackup="false"` (app.json,
 *   enforced by `npm run release:preflight`). It is written anyway because an
 *   ABSENT section is not a denial: `FullBackup.parseSchemeForBackupDestination`
 *   only treats the new scheme as authoritative when it finds the matching
 *   section, and falls through to "no rules at all" - i.e. copy everything -
 *   when it does not. A rules file that covered only device transfer would be a
 *   trap for whoever eventually flips `allowBackup`.
 *
 * - `device-transfer` is the section that closes the actual gap. Android's own
 *   documentation: "On devices from some device manufacturers, specifying
 *   `android:allowBackup="false"` disables cloud-based backup and restore (such
 *   as Google Drive backups) but doesn't disable device-to-device transfers for
 *   the app." The platform reinforces it - `IGNORE_FULL_BACKUP_CONTENT_IN_D2D`
 *   is `@EnabledSince(targetSdkVersion = S)`, so for a modern target the legacy
 *   `fullBackupContent` rules are ignored during D2D and this section is the
 *   ONLY thing that speaks for it.
 *
 * NOT WRITTEN: `cross-platform-transfer`. It exists in the Android 36 sources
 * but is gated behind the unreleased `Flags.enableCrossPlatformTransfer()`
 * aconfig flag, is absent from the public documentation, and its schema (a
 * `platform` attribute plus `<platform-specific-params/>`) is not stable. No
 * shipping Android release performs it, so writing a guess at it today would be
 * speculative. Revisit when the API is documented.
 */
const EXTRACTION_SECTIONS = ['cloud-backup', 'device-transfer'];

const HEADER_NOTE = `  Red Panda denies BOTH cloud backup and device-to-device transfer of all
  app-private storage.

  WHAT IS BEING PROTECTED. Two different stores, for two different reasons:

   - AsyncStorage, a SQLite database under databases/ (RKStorage). It holds
     the signed-in account's NON-SECRET metadata under "@mobile-app-ecc/auth"
     (id, name, username, email - see src/services/auth/persisted-account.ts),
     plus likes, saved videos, watch progress, their sync queues, and device
     preferences. Since the secure-session work it holds NO bearer token.
   - SecureStore's own SharedPreferences file ("SecureStore"), which holds the
     access/refresh pair as AES-256-GCM ciphertext under an Android Keystore
     key (src/services/auth/session-secret-store.ts). The sharedpref and
     device_sharedpref excludes below are what cover it.

  THE TWO PROTECTIONS ARE SEPARATE AND BOTH ARE NEEDED. This file is BACKUP /
  TRANSFER protection: it stops the OS copying this app's data off the device.
  Keystore encryption is AT-REST protection: it stops the token being readable
  in the copy that stays. Neither substitutes for the other, and this policy
  still matters with tokens encrypted - the account metadata, the watch
  history and the ciphertext itself are all still worth not shipping to a new
  handset unasked.

  WHY DENY-ALL RATHER THAN EXCLUDING ONE KEY: AsyncStorage is one database
  file. There is no path that names one key inside it, so the narrowest rule
  that can exclude anything in it already excludes the whole store - and once
  the store is gone, the remaining candidates (a language choice, an
  ad-frequency counter) are not worth an allow rule that would have to be
  re-audited every time something new is persisted. Nothing here is lost data:
  likes, saves and watch progress live on the backend and are re-merged at
  first login on the new device.

  THIS FILE IS THE ONLY BACKUP AUTHORITY. expo-secure-store ships a config
  plugin that would write its OWN android:dataExtractionRules - an
  include-based policy covering only its own prefs file, which is strictly
  weaker than the deny-all below. app.json therefore registers it with
  { "configureAndroidBackup": false }, and npm run release:preflight fails the
  build if that is ever dropped.

  NO <include> ELEMENT APPEARS BELOW, DELIBERATELY. An empty include set means
  "everything except the excludes" - the excludes are the whole policy, which
  is why they enumerate every domain rather than relying on an implicit deny.

  This is an EXTRACTION policy, not encryption: it stops this app's data from
  being copied off the device by the OS. It makes no claim, by itself, about
  data at rest - and AsyncStorage is NOT encrypted by anything here.`;

/** One `<exclude/>` line per domain, indented for the section it sits in. */
function renderExcludes(indent) {
  return EXCLUDED_DOMAINS.map(
    (domain) => `${indent}<exclude domain="${domain}" path="${DOMAIN_ROOT_PATH}" />`
  ).join('\n');
}

function renderSection(section) {
  return `    <${section}>
${renderExcludes('        ')}
    </${section}>`;
}

/**
 * The whole resource, as a pure function of the constants above. Deterministic
 * by construction - it reads nothing and takes no arguments - so a repeated
 * `expo prebuild` writes byte-identical content.
 */
function renderDataExtractionRules() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  ${GENERATED_MARKER} - do not edit by hand.

${HEADER_NOTE}
-->
<data-extraction-rules>
${EXTRACTION_SECTIONS.map(renderSection).join('\n')}
</data-extraction-rules>
`;
}

/**
 * Deletes a generated copy of this resource from any variant source set.
 *
 * `android/` is gitignored and regenerated, but `expo prebuild` WITHOUT
 * `--clean` regenerates it IN PLACE - so a variant-scoped override written by
 * an earlier configuration would survive into a build made from the same
 * working tree, silently shadowing `main` for that variant only. Since the
 * policy is now unconditional, ANY variant copy is stale by definition.
 *
 * Narrow on purpose, exactly like the sibling cleartext plugin: a file is
 * removed only when it carries this plugin's own generated marker.
 */
function removeStaleVariantResources(platformProjectRoot) {
  for (const relativePath of VARIANT_RESOURCE_RELATIVE_PATHS) {
    const resourcePath = path.join(platformProjectRoot, relativePath);

    if (!fs.existsSync(resourcePath)) {
      continue;
    }

    if (fs.readFileSync(resourcePath, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(resourcePath);
    }
  }
}

/**
 * Gives the Android build an `android:dataExtractionRules` policy that denies
 * cloud backup AND device-to-device transfer of every app-private domain.
 *
 * WHY THIS EXISTS AT ALL, GIVEN allowBackup="false" IS ALREADY SET. Those two
 * settings answer different questions. `allowBackup="false"` withdraws the app
 * from OS-driven cloud backup - the Google Drive copy - and that is genuinely
 * settled. It does NOT settle device-to-device transfer: Android's own
 * documentation says that for an app targeting Android 12 or higher,
 * `android:allowBackup="false"` "disables cloud-based backup and restore (such
 * as Google Drive backups) but doesn't disable device-to-device transfers for
 * the app" on some manufacturers' devices. So on the "set up your new phone
 * from your old phone" path - the single most ordinary way an Android user
 * moves - this app's AsyncStorage database, and SecureStore's encrypted
 * SharedPreferences beside it, could be copied onto the new handset while the
 * app itself was never asked. `<device-transfer>` is the only mechanism that
 * answers that,
 * and Expo emits neither the attribute nor the resource (nothing in the
 * installed `@expo/config-plugins` or `@expo/prebuild-config` mentions
 * `dataExtractionRules`), so it has to be written here.
 *
 * WHY A CONFIG PLUGIN AND NOT AN EDITED FILE: `android/` is gitignored and
 * regenerated by `expo prebuild`. An XML resource typed into it by hand is
 * destroyed by the next prebuild and the artifact after that one silently
 * loses the policy - the same reasoning that makes release signing a plugin
 * (see plugins/with-android-release-signing.js).
 *
 * WHAT IT DOES NOT DO: it does not encrypt anything, and it does not make the
 * tokens safe on a rooted or physically compromised device. It removes one
 * specific, OS-driven copy path off the device. That is the whole claim.
 *
 * UNCONDITIONAL, unlike the cleartext plugin next to it. That one keys off the
 * backend scheme because a cleartext exemption is only ever correct for one
 * kind of build; this policy is correct for every build there is, including
 * development - nothing in `expo start`, `expo run:android` or an internal
 * demo APK depends on backup or transfer, and losing it would not be noticed
 * until it mattered.
 */
module.exports = function withAndroidDataExtractionRules(config) {
  config = withDangerousMod(config, [
    'android',
    (dangerousConfig) => {
      const { platformProjectRoot } = dangerousConfig.modRequest;
      const resourcePath = path.join(platformProjectRoot, RESOURCE_RELATIVE_PATH);

      fs.mkdirSync(path.dirname(resourcePath), { recursive: true });
      fs.writeFileSync(resourcePath, renderDataExtractionRules(), 'utf8');

      removeStaleVariantResources(platformProjectRoot);

      return dangerousConfig;
    },
  ]);

  return withAndroidManifest(config, (manifestConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifestConfig.modResults);

    application.$[MANIFEST_ATTRIBUTE] = CONFIG_RESOURCE_REFERENCE;

    return manifestConfig;
  });
};

