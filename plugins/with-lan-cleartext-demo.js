const fs = require('fs');
const path = require('path');

const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const CONFIG_RESOURCE = 'network_security_config';

// Stamped into every file this plugin writes, and checked before it deletes
// one. A `network_security_config.xml` that some other plugin (or a human)
// put there is none of this plugin's business - only what it generated
// itself may ever be removed.
const GENERATED_MARKER = 'GENERATED by plugins/with-lan-cleartext-demo.js';

const CONFIG_RESOURCE_REFERENCE = `@xml/${CONFIG_RESOURCE}`;

function resourceRelativePath(sourceSet) {
  return path.join('app', 'src', sourceSet, 'res', 'xml', `${CONFIG_RESOURCE}.xml`);
}

const RESOURCE_RELATIVE_PATH = resourceRelativePath('main');
const DEBUG_RESOURCE_RELATIVE_PATH = resourceRelativePath('debug');

/**
 * The Metro dev server, reached over `adb reverse tcp:8081 tcp:8081`.
 *
 * WHY THIS EXISTS AT ALL. Declaring `android:networkSecurityConfig` makes
 * Android IGNORE `android:usesCleartextTraffic`, including the `true` the
 * Expo template sets in the `debug`/`debugOptimized` manifests. So the
 * moment this plugin becomes active - i.e. whenever the build points at an
 * `http://` backend - the single-`<domain>` config below silently revoked
 * the debug build's permission to talk to Metro, and `expo run:android`
 * died with:
 *
 *   The packager does not seem to be running as we got an IOException
 *   requesting its status: CLEARTEXT communication to localhost not
 *   permitted by network security policy
 *   ... java.lang.RuntimeException: Unable to load script.
 *
 * The app then sat on its splash screen forever. Observed on a physical
 * device (Android 15) during Android HLS runtime verification, 2026-08-25.
 *
 * DEBUG-ONLY on purpose. Android merges `src/debug/res` over `src/main/res`
 * for the debug variant only, so the release artifact keeps the
 * byte-for-byte single-host config it has today and gains no localhost
 * permission of any kind. A release APK bundles its JavaScript and never
 * contacts Metro, so it has no reason to want one.
 */
const DEV_SERVER_DOMAINS = ['localhost', '127.0.0.1'];

/**
 * Collapses a domain list to the unique hosts Android will accept, keeping
 * first-seen order so the generated resource stays deterministic.
 *
 * THIS IS LOAD-BEARING, NOT TIDINESS. Android does NOT treat repeated
 * `<domain>` values as a harmless set - `XmlConfigSource.parseDomain` throws
 * `ParserException: <host> has already been specified`, which surfaces as
 * `Failed to parse XML configuration from network_security_config` and kills
 * the process in `LoadedApk.makeApplicationInner`, BEFORE React Native or any
 * JavaScript runs. There is no splash, no error screen, and no JS error
 * boundary that can catch it: the app simply never opens.
 *
 * The duplicate is not hypothetical. The debug source set is rendered as
 * `[host, ...DEV_SERVER_DOMAINS]`, so ANY build whose API host is itself a
 * dev-server domain - `EXPO_PUBLIC_API_BASE_URL=http://localhost:3000`, the
 * value this repo ships in `.env` - emitted `localhost` twice and could not
 * start. Normalising here rather than at the call site means no future caller
 * can reintroduce it by concatenating one more list.
 *
 * Hostnames are case-insensitive, so comparison is done lowercased; empty and
 * whitespace-only entries are dropped rather than emitted as a `<domain>` that
 * matches nothing.
 *
 * @param {readonly string[]} domains
 * @returns {string[]} unique, normalised hosts in first-seen order
 */
function normalizeDomains(domains) {
  const seen = new Set();

  return domains.reduce((unique, domain) => {
    const normalized = String(domain).trim().toLowerCase();

    if (normalized === '' || seen.has(normalized)) {
      return unique;
    }

    seen.add(normalized);

    return [...unique, normalized];
  }, []);
}

/**
 * Renders the resource for one source set.
 *
 * Every `<domain>` it emits is unique - see `normalizeDomains` for why a
 * duplicate is a startup crash rather than a cosmetic flaw.
 */
function renderNetworkSecurityConfig(domains, note) {
  const entries = normalizeDomains(domains)
    .map((domain) => `        <domain includeSubdomains="false">${domain}</domain>`)
    .join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  ${GENERATED_MARKER} - do not edit by hand.

${note}
-->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
${entries}
    </domain-config>
</network-security-config>
`;
}

const MAIN_NOTE = `  Cleartext HTTP is permitted for this ONE host only, because an internal
  demo build points at a local backend on the LAN. Every other destination
  keeps Android's default cleartext-denied behaviour.`;

const DEBUG_NOTE = `  DEBUG VARIANT ONLY (src/debug/res overrides src/main/res for the debug
  build). Same LAN backend host as the main config, PLUS the Metro dev
  server on localhost - declaring a networkSecurityConfig makes Android
  ignore the debug manifest's usesCleartextTraffic="true", which would
  otherwise block the JS bundle download and hang the app on its splash.
  The release config is unaffected and grants no localhost permission.`;

/**
 * Reads the API host the build is actually pointed at, and decides whether
 * this build needs a cleartext exemption at all.
 *
 * Static property access, not `process.env[key]` - the same rule
 * `services/auth/google-sign-in-contract.ts` follows. (Here it runs in Node
 * at prebuild time so either form would work; keeping one rule across the
 * repo is what stops the runtime version being written the wrong way by
 * copy-paste.)
 */
function resolveCleartextHost() {
  const apiBaseUrl = process.env.EXPO_PUBLIC_API_BASE_URL;

  if (!apiBaseUrl) {
    return null;
  }

  let parsed;

  try {
    parsed = new URL(apiBaseUrl);
  } catch {
    throw new Error(
      `with-lan-cleartext-demo: EXPO_PUBLIC_API_BASE_URL is not a valid URL: "${apiBaseUrl}". ` +
        'Fix it before building - a malformed backend URL produces an APK that cannot reach ' +
        'any backend at all.'
    );
  }

  // https needs no exemption, which is the whole point of keying off the
  // scheme: a build pointed at a real https backend gets NO cleartext
  // permission of any kind, and it withdraws automatically rather than by
  // anyone remembering to remove it. `null` here does not mean "do nothing" -
  // see `withoutCleartextExemption`, which actively clears what a previous
  // http prebuild may have left in place.
  return parsed.protocol === 'http:' ? parsed.hostname : null;
}

/**
 * The https / no-backend branch: not merely "add nothing", but "make sure
 * nothing is there".
 *
 * `android/` is gitignored and regenerated, but `expo prebuild` WITHOUT
 * `--clean` regenerates it in place - and a plugin that simply returns early
 * removes neither the resource a PREVIOUS http prebuild wrote nor the
 * `android:networkSecurityConfig` attribute it set on the manifest. So the
 * same working tree that built the internal LAN demo could then build a
 * production APK still carrying a cleartext exemption for a private LAN
 * address, purely because nobody thought to wipe `android/` in between.
 *
 * Nothing in the app would USE that exemption (a production build only ever
 * calls its https base URL), which is why this is a hygiene fix rather than a
 * live vulnerability - but "the artifact contains no cleartext permission at
 * all" is the property worth being able to state without qualification, and
 * the only way to state it is to actively assert it.
 *
 * Deliberately narrow: it removes a resource file only when that file carries
 * this plugin's own generated marker, and clears the manifest attribute only
 * when it points at this plugin's own resource.
 */
function withoutCleartextExemption(config) {
  config = withDangerousMod(config, [
    'android',
    (dangerousConfig) => {
      for (const relativePath of [RESOURCE_RELATIVE_PATH, DEBUG_RESOURCE_RELATIVE_PATH]) {
        const resourcePath = path.join(
          dangerousConfig.modRequest.platformProjectRoot,
          relativePath
        );

        if (!fs.existsSync(resourcePath)) {
          continue;
        }

        if (fs.readFileSync(resourcePath, 'utf8').includes(GENERATED_MARKER)) {
          fs.rmSync(resourcePath);
        }
      }

      return dangerousConfig;
    },
  ]);

  return withAndroidManifest(config, (manifestConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifestConfig.modResults);

    if (application.$['android:networkSecurityConfig'] === CONFIG_RESOURCE_REFERENCE) {
      delete application.$['android:networkSecurityConfig'];
    }

    return manifestConfig;
  });
}

/**
 * Permits cleartext HTTP to exactly ONE host: the LAN address of the
 * developer machine serving the local backend for an internal demo build.
 *
 * WHY THIS EXISTS: Android 9 (API 28) and newer refuse cleartext HTTP by
 * default. The Expo template only sets `usesCleartextTraffic="true"` in the
 * `debug` and `debugOptimized` manifests, so a RELEASE APK - the
 * self-contained artifact worth handing to a reviewer, because its
 * JavaScript is bundled inside and it needs no Metro - silently fails every
 * request to `http://<lan-ip>:3000`. The app then renders its ordinary
 * error states, so a blocked protocol looks exactly like a broken product.
 *
 * WHY IT IS NOT `usesCleartextTraffic="true"`: that flag is
 * application-wide and permanent. It would let ANY code path in ANY build
 * talk plaintext to ANY host, including a production build that inherited
 * the flag by accident. A `network_security_config` scoped to a single
 * `<domain>` is the narrow version of the same permission -
 * `cleartextTrafficPermitted` stays FALSE everywhere else, so a stray
 * `http://` call to anywhere but the demo backend still fails exactly as it
 * does today.
 *
 * WHY IT IS SAFE IN PRODUCTION: it is keyed off the scheme of
 * `EXPO_PUBLIC_API_BASE_URL`, the same value the app itself calls. Point a
 * build at an `https://` backend (or at nothing) and this plugin adds no
 * resource, no manifest attribute and no exemption - and REMOVES any it
 * previously wrote, so an incremental prebuild over an existing `android/`
 * cannot inherit one (see `withoutCleartextExemption` above). There is no
 * separate flag to remember to switch off, because the unsafe state is not
 * expressible: cleartext is permitted only for a host the build is already
 * talking to in cleartext.
 *
 * This does NOT weaken authentication. Token handling, OTP verification and
 * entitlement checks are untouched; only the transport to one LAN address
 * is permitted, for an internal build on a trusted network.
 */
module.exports = function withLanCleartextDemo(config) {
  const host = resolveCleartextHost();

  if (!host) {
    return withoutCleartextExemption(config);
  }

  config = withDangerousMod(config, [
    'android',
    (dangerousConfig) => {
      const write = (relativePath, contents) => {
        const resourcePath = path.join(
          dangerousConfig.modRequest.platformProjectRoot,
          relativePath
        );

        fs.mkdirSync(path.dirname(resourcePath), { recursive: true });
        fs.writeFileSync(resourcePath, contents, 'utf8');
      };

      write(RESOURCE_RELATIVE_PATH, renderNetworkSecurityConfig([host], MAIN_NOTE));
      write(
        DEBUG_RESOURCE_RELATIVE_PATH,
        renderNetworkSecurityConfig([host, ...DEV_SERVER_DOMAINS], DEBUG_NOTE)
      );

      return dangerousConfig;
    },
  ]);

  return withAndroidManifest(config, (manifestConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifestConfig.modResults);

    application.$['android:networkSecurityConfig'] = CONFIG_RESOURCE_REFERENCE;

    return manifestConfig;
  });
};

